def _assert_valid_trained_energies(
    energies, expected_count, expect_zero_isolated=True
):
    """Check the CLI artifact without pinning it to an unrelated training policy.

    The historical exact vectors below were generated by upstream full-MACE
    training in 2023/2024.  This branch already used an ELoRA-specific gradient
    whitelist before Goal 0, so those values are not a valid reproducibility
    oracle.  Determinism and parameter ownership are tested directly in
    ``test_elora_readiness.py``.
    """
    values = np.asarray(energies)
    assert values.shape == (expected_count,)
    assert np.isfinite(values).all()
    if expect_zero_isolated:
        assert np.allclose(values[:2], 0.0)
    assert np.ptp(values[2:]) > 0.0


def test_run_train(tmp_path, fitting_configs):
    ase.io.write(tmp_path / "fit.xyz", fitting_configs)

    mace_params = _mace_params.copy()
    mace_params["checkpoints_dir"] = str(tmp_path)
    mace_params["model_dir"] = str(tmp_path)
    mace_params["train_file"] = tmp_path / "fit.xyz"

    # make sure run_train.py is using the mace that is currently being tested
    run_env = os.environ.copy()
    sys.path.insert(0, str(Path(__file__).parent.parent))
    run_env["PYTHONPATH"] = os.pathsep.join(sys.path)
    print("DEBUG subprocess PYTHONPATH", run_env["PYTHONPATH"])

    cmd = (
        sys.executable
        + " "
        + str(run_train)
        + " "
        + " ".join(
            [
                (f"--{k}={v}" if v is not None else f"--{k}")
                for k, v in mace_params.items()
            ]
        )
    )

    p = subprocess.run(cmd.split(), env=run_env, check=True)
    assert p.returncode == 0

    calc = MACECalculator(tmp_path / "MACE.model", device="cpu")

    Es = []
    for at in fitting_configs:
        at.calc = calc
        Es.append(at.get_potential_energy())

    print("Es", Es)
    _assert_valid_trained_energies(Es, len(fitting_configs))


